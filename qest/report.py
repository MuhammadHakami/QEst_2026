"""Collect results/ into results/RESULTS.md (+ results/cumulative_test.png).
usage: .venv/bin/python -m qest.report
"""
import pandas as pd

from qest.paths import RESULTS

COMP = ['cap', 'da', 'mfrr', 'afrr', 'imbalance', 'penalty', 'leftover', 'tariff', 'total']


def eur(x):
    return f'{x / 1e6:,.2f} M' if abs(x) >= 1e5 else f'{x / 1e3:,.0f} k'


def strategy_table(split, settlement):
    p = RESULTS / f'summary_{split}_{settlement}.csv'
    if not p.exists():
        return None
    t = pd.read_csv(p, index_col=0)
    d = pd.read_parquet(RESULTS / f'days_{split}_{settlement}.parquet')
    units = d.groupby(['strategy', 'unit']).total.sum().unstack()
    out = pd.DataFrame({'total EUR': t.total.map(eur)})
    for c in ('cap', 'da', 'mfrr', 'afrr', 'imbalance', 'penalty'):
        out[c] = t[c].map(eur)
    for u in units:
        out[u] = units[u].reindex(t.index).map(eur)
    out['undelivered MWh'] = t.undelivered_mwh.round(0).astype(int)
    out['% of oracle'] = (t.total / t.total.get('oracle', float('nan')) * 100).round(1)
    return out


def qubo_table():
    """Retrospective puzzle (slide 9/12): every solver's EUR as a share of the exact classical optimum."""
    from qest.figures import QLABEL, quantum
    T = quantum('retro')
    if T.empty:
        return None
    T = T.assign(method=T.solver.map(QLABEL), EUR=T.eur.map(eur), **{'% of optimum': T.pct.round(2), 'optimum hit': T.opt.round(3),
                 'P(optimum) in quantum state': T.popt.round(3), 's/instance': T.s.map(lambda x: f'{x:.2g}')})
    return T[['level', 'qubits', 'n', 'method', 'EUR', '% of optimum', 'optimum hit', 'P(optimum) in quantum state', 's/instance']]


def cumulative_plot():
    import matplotlib
    matplotlib.use('Agg'); import matplotlib.pyplot as plt
    p = RESULTS / 'days_test_official.parquet'
    if not p.exists():
        return
    d = pd.read_parquet(p).groupby(['day', 'strategy']).total.sum().unstack().cumsum() / 1e6
    ax = d.drop(columns=['oracle']).plot(figsize=(9, 4.5), lw=2)
    d['oracle'].plot(ax=ax, ls='--', color='grey', label='oracle (hindsight)')
    ax.set_ylabel('cumulative EUR (millions)'); ax.set_xlabel('Q4 delivery day (Tallinn)'); ax.set_title('Q4 test, official scoring (slides 10 + 12): battery + hybrid')
    ax.legend(ncol=2, fontsize=8); ax.grid(alpha=.3); plt.tight_layout(); plt.savefig(RESULTS / 'cumulative_test.png', dpi=130)


def main():
    out = ['# Results', '', 'Generated by `python -m qest.report` from `results/`. EUR over the whole split. Official scoring (organisers\' deck v3, slides 10 + 12) '
           'covers the deck\'s two sites: battery 100 MW / 200 MWh + hybrid (PV 20 MW + 20 MW / 40 MWh, 20 MW connection). Baltic and starter '
           'modes add the Pihlaka solar park (42.3 MW) and the Paldiski wind park (45 MW).', '']
    for split, name in (('test', 'Q4 test (1-25 Oct), forecasts refitted on Q1-Q3'), ('val', 'Q3 validation, forecasts fitted on Q1-Q2')):
        for st in ('official', 'baltic', 'starter'):
            t = strategy_table(split, st)
            if t is not None:
                out += [f'## {name}: {st} settlement', '', t.to_markdown(), '']
    rl = RESULTS / 'rl_ppo.csv'
    if rl.exists():
        r = pd.read_csv(rl); g = r.groupby('split')
        out += ['## RL: PPO (Stable-Baselines3) choosing the MILP knobs per day (qest.gym_env), official scoring', '',
                'Trained on Q3 days only (so its Q3 figure is in-sample); Q4 scored once with the deterministic policy.', '',
                pd.DataFrame({'EUR': g.eur.sum().map(eur), 'mean kappa_up': g.kappa_up.mean().round(3), 'mean kappa_dn': g.kappa_dn.mean().round(3),
                              'mean tol': g.tol.mean().round(3)}).to_markdown(), '']
    try:
        from qest.data import days, frame
        from qest.evaluate import forecasts
        from qest.forecast import skill
        f = frame(); rows = {}
        for sp in ('val', 'test'):
            D = days(f, sp)
            for name, k in (('Chronos-2', 'chronos'), ('LightGBM', 'lgbm'), ('persistence', 'persist')):
                if (RESULTS / f'forecast_{k}_{sp}.parquet').exists():
                    rows[(sp, name)] = skill(forecasts(sp, k), D).mae
        if rows:
            out += ['## Gate-A forecast MAE (val = Q3 fitted on Q1-Q2; test = Q4, LightGBM/persistence chosen per target on Q3)', '',
                    pd.DataFrame(rows).round(2).to_markdown(), '']
    except Exception as e:  # report what is there; a missing cache is not fatal
        out += [f'(forecast skill skipped: {e})', '']
    q = qubo_table()
    if q is not None:
        out += ['## Quantum track: the portfolio puzzle (slide 11), retrospective, every Q4 hour', '',
                'Prices known (slide 9): each solver\'s plan as a share of the exact classical optimum; infeasible plans score 0. '
                '"optimum hit" = the returned plan is the optimum; "P(optimum)" = probability mass on it in the simulated quantum '
                'state, before the shared one-bit polish. "random + polish" is the control: random bits through the same polish.', '',
                q.to_markdown(index=False), '']
    t = RESULTS / 'tune_optuna.csv'
    if t.exists():
        T = pd.read_csv(t)[['number', 'value', 'params_afrr', 'params_mfrr', 'params_kappa_up', 'params_kappa_dn', 'params_tol']].head(8)
        out += ['## MILP knobs tuned by Optuna (TPE) on Q3, official scoring, battery + hybrid', '', T.round(3).to_markdown(index=False), '']
    cumulative_plot()
    if (RESULTS / 'cumulative_test.png').exists():
        out += ['![cumulative](cumulative_test.png)', '']
    (RESULTS / 'RESULTS.md').write_text('\n'.join(out))
    print('\n'.join(out))


if __name__ == '__main__':
    main()
